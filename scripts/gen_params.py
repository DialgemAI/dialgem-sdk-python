"""Generate src/dialgem/types/params.py (request-body TypedDicts) from openapi/openapi.json.

    python scripts/gen_params.py            # rewrite the file
    python scripts/gen_params.py --check    # exit 1 if the committed file is stale (CI)

Only the top level of each request body is typed. A nested object is ``Dict[str, Any]``: a
conversation-flow definition is a large discriminated union the server validates, and
modelling it here would make the SDK reject shapes the server has since learned to accept.
Enums and constants are kept as ``Literal`` so editors can complete them.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi" / "openapi.json"
OUT = ROOT / "src" / "dialgem" / "types" / "params.py"

#: (Python name, OpenAPI schema name)
REQUESTS = [
    ("AgentCreateParams", "AgentCreate"),
    ("AgentUpdateParams", "AgentUpdate"),
    ("FunctionCreateParams", "FunctionCreate"),
    ("FunctionUpdateParams", "FunctionUpdate"),
    ("FunctionReorderParams", "FunctionReorder"),
    ("KnowledgeDocumentCreateParams", "DocumentCreate"),
    ("MCPServerCreateParams", "MCPServerCreate"),
    ("MCPServerUpdateParams", "MCPServerUpdate"),
    ("PhoneNumberCreateParams", "PhoneNumberCreate"),
    ("PhoneNumberUpdateParams", "PhoneNumberUpdate"),
    ("PhoneNumberAssignParams", "PhoneNumberAssign"),
    ("CallCreatePhoneCallParams", "OutboundCallRequest"),
    ("CallRegisterParams", "RegisterCallRequest"),
    ("ChatCreateParams", "ChatCreate"),
    ("FlowCreateParams", "FlowCreate"),
    ("LLMCreateParams", "LLMCreate"),
    ("SessionUpdateParams", "SessionUpdate"),
    ("SessionSayParams", "SessionSay"),
    ("LLMUpdateParams", "LLMUpdate"),
    ("WebCallCreateParams", "WebCallRequest"),
    ("WebCallSettingsUpdateParams", "WebCallSettings"),
    ("ContactCreateParams", "ContactCreate"),
    ("ContactUpdateParams", "ContactUpdate"),
    ("ContactImportCreateParams", "ContactImportCreate"),
    ("ContactListCreateParams", "ContactListCreate"),
    ("ContactListUpdateParams", "ContactListUpdate"),
    ("SimulationSuiteCreateParams", "SuiteCreate"),
    ("SimulationSuiteUpdateParams", "SuiteUpdate"),
    ("SimulationCaseParams", "CaseBody"),
    ("SimulationCaseUpdateParams", "CaseUpdate"),
    ("SimulationRunCreateParams", "RunCreate"),
]

#: Enum aliases worth exporting by name: (alias, schema, property)
ALIASES = [
    ("AgentType", "AgentCreate", "agent_type"),
    ("FunctionKind", "FunctionCreate", "kind"),
]


def render(schemas: dict) -> str:
    def ref_schema(ref: str) -> dict:
        return schemas[ref.rsplit("/", 1)[-1]]

    def ty(node: dict) -> str:
        if "$ref" in node:
            target = ref_schema(node["$ref"])
            if "enum" in target or "const" in target:
                return ty(target)
            return "Dict[str, Any]"
        if "const" in node:
            return f"Literal[{node['const']!r}]"
        if "enum" in node:
            return "Literal[" + ", ".join(repr(v) for v in node["enum"]) + "]"
        for key in ("anyOf", "oneOf"):
            if key in node:
                parts: list[str] = []
                for sub in node[key]:
                    r = "None" if sub.get("type") == "null" else ty(sub)
                    if r not in parts:
                        parts.append(r)
                return parts[0] if len(parts) == 1 else "Union[" + ", ".join(parts) + "]"
        t = node.get("type")
        if t == "string":
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "Union[int, float]"
        if t == "boolean":
            return "bool"
        if t == "array":
            return f"List[{ty(node['items'])}]" if "items" in node else "List[Any]"
        if t == "object":
            return "Dict[str, Any]"
        return "Any"

    out = [
        '"""Request-body types.',
        "",
        "GENERATED by scripts/gen_params.py from openapi/openapi.json. Do not edit by hand.",
        "",
        "Field names are the API's own (snake_case) and are sent exactly as written. Pass them as",
        "keyword arguments: ``dialgem.agents.create(name=\"Front desk\", system_prompt=\"...\")``.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Literal, Union",
        "",
        "from typing_extensions import Required, TypedDict",
        "",
    ]
    for alias, schema, prop in ALIASES:
        out.append(f"{alias} = {ty(schemas[schema]['properties'][prop])}")
    out.append("")
    out.append("#: Which published agent version a number or call uses. 0 is the live draft.")
    out.append('AgentVersionRef = Union[int, Literal["latest_published"]]')
    out.append("")
    for pyname, sname in REQUESTS:
        schema = schemas[sname]
        required = set(schema.get("required", []))
        out.append("")
        out.append(f"class {pyname}(TypedDict, total=False):")
        out.append(f'    """Body of the request. Schema: ``{sname}``."""')
        out.append("")
        props = schema.get("properties", {})
        if not props:
            out.append("    pass")
        for name, node in props.items():
            ann = ty(node)
            if name in required:
                ann = f"Required[{ann}]"
            desc = (node.get("description") or "").strip().replace("\n", " ")
            if desc:
                out.append(f"    #: {desc}")
            out.append(f"    {name}: {ann}")
    return "\n".join(out) + "\n"


def main() -> int:
    schemas = json.loads(SNAPSHOT.read_text(encoding="utf8"))["components"]["schemas"]
    text = render(schemas)
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf8") != text:
            print("types/params.py is stale: run `python scripts/gen_params.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(REQUESTS)} request bodies)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
