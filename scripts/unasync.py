"""Generate src/dialgem/aresources/ (async resources) from src/dialgem/resources/ (sync).

    python scripts/unasync.py            # rewrite
    python scripts/unasync.py --check    # exit 1 if stale (CI)

The sync resources are the source of truth. The conventions that make the transform safe:

* a method is ``def name(...)`` at class level whose body is ``return self._client.<verb>(...)``;
* a method that calls ``self._client.paginate(`` returns a page object and stays a plain ``def``
  (the async paginator is awaitable and async-iterable, so it must not itself be a coroutine);
* helpers outside classes are pure functions and are copied unchanged.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "dialgem" / "resources"
DST = ROOT / "src" / "dialgem" / "aresources"

HEADER = (
    "# GENERATED by scripts/unasync.py from dialgem/resources/{name}. Do not edit by hand:\n"
    "# edit the sync file and run `python scripts/unasync.py`.\n"
)

METHOD = re.compile(r"^    def (?!__)(\w+)\(", re.M)


def transform(text: str, name: str) -> str:
    # Split the text into method chunks so each can be judged by its own body.
    starts = [m.start() for m in METHOD.finditer(text)]
    if not starts:
        out = text
    else:
        pieces = [text[: starts[0]]]
        bounds = starts + [len(text)]
        for lo, hi in zip(bounds, bounds[1:], strict=False):
            chunk = text[lo:hi]
            # A chunk may run on into a module-level helper or the next class; cut at the first dedent to col 0.
            tail_at = re.search(r"^\S", chunk, re.M)
            body, tail = (chunk[: tail_at.start()], chunk[tail_at.start() :]) if tail_at else (chunk, "")
            if "self._client.paginate(" in body:
                body = body.replace("SyncPage[", "AsyncPaginator[")
            else:
                body = METHOD.sub(lambda m: f"    async def {m.group(1)}(", body, count=1)
                body = body.replace("return self._client.", "return await self._client.")
            pieces.append(body + tail)
        out = "".join(pieces)
    out = re.sub(r"^class (\w+)\(Resource\):", r"class Async\1(AsyncResource):", out, flags=re.M)
    out = re.sub(r"= ([A-Z]\w+)\(client\)", r"= Async\1(client)", out)
    out = re.sub(r"^from dialgem\._resource import Resource\b", "from dialgem._resource import AsyncResource", out, flags=re.M)
    out = out.replace("from dialgem._pagination import SyncPage", "from dialgem._pagination import AsyncPaginator")
    out = out.replace("SyncPage[", "AsyncPaginator[")
    out = out.replace("SyncAPIClient", "AsyncAPIClient")
    return HEADER.format(name=name) + out


def main() -> int:
    check = "--check" in sys.argv
    DST.mkdir(exist_ok=True)
    expected = {}
    for path in sorted(SRC.glob("*.py")):
        if path.name == "__init__.py":
            continue
        expected[path.name] = transform(path.read_text(encoding="utf8"), path.name)
    mods = sorted(n[:-3] for n in expected)
    expected["__init__.py"] = (
        '"""GENERATED async resources. See scripts/unasync.py."""\n\nfrom dialgem.aresources import (  # noqa: F401\n'
        + "".join(f"    {m},\n" for m in mods)
        + ")\n"
    )
    stale = []
    for name, text in expected.items():
        target = DST / name
        if check:
            if not target.exists() or target.read_text(encoding="utf8") != text:
                stale.append(name)
        else:
            target.write_text(text, encoding="utf8", newline="\n")
    if check:
        for stray in DST.glob("*.py"):
            if stray.name not in expected:
                stale.append(stray.name)
        if stale:
            print("aresources is stale: " + ", ".join(sorted(stale)) + ". Run `python scripts/unasync.py`.", file=sys.stderr)
            return 1
        return 0
    print(f"wrote {len(expected)} files to {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
